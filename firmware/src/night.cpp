// Нічна тиша (нове, не з оригіналу).
// EN: Night quiet (new): while the display is off at night, content and its downloads are paused.
// Задача: поки табло погашене на ніч, не робити непотрібних опитувань — до повернення в робочий режим.
// У автора при погашеному табло (D=1, вночі за розкладом) вміст крутився далі: новини,
// погода, курси, анекдоти, YouTube, народмон (показ) вантажились і бігли невидимим табло (спостереження: нова новина о 00:04
// при погаслому табло), плюс перевірка версії й мовного пакета. Тепер, поки табло погашене (розклад або MQTT),
// цикл вмісту стоїть (датчики читаються далі — для MQTT, народмону й історії), без перевірки версії й мови.
// Лишаються: Wi-Fi і перевірка інтернету (веб-інтерфейс доступний уночі), NTP, MQTT, відправка на народмон, історія,
// будильник, стрічка й звук зі своїми нічними режимами. Уранці вміст продовжується з того місця, де зупинився,
// а дані, що застаріли за ніч, оновлюються при першому ж показі.
#include "fw.h"

bool g_fx_quiet;

void fx_night_tick() {
  bool q = (g_c1a28 != 0 || g_c3080 != 0) && g_c3001 == 0;   // g_c3001 — показ повідомлення
  if (q == g_fx_quiet) return;
  g_fx_quiet = q;
  dbg_ws_print(String(q ? "Night quiet : display off — content and its downloads paused"
                        : "Night quiet : display on — content resumed"));
}
